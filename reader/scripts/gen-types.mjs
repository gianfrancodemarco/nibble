// Generates src/visual/types.gen.d.ts from protocol/schemas/*.schema.json.
// Output is ambient (no exports): the app build is module:none — one global
// scope — so the generated names are visible everywhere without imports.
import { compile } from "json-schema-to-typescript";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const schemasDir = path.join(here, "..", "..", "protocol", "schemas");
const outFile = path.join(here, "..", "src", "visual", "types.gen.d.ts");

const kinds = ["map", "sequence", "timeline", "compare"];
const parts = [
  "// GENERATED by `npm run gen` from protocol/schemas/*.schema.json — do not edit.",
  "// CI regenerates and fails on drift, like it does for app.js.",
  "",
];

const names = [];
for (const kind of kinds) {
  const raw = await readFile(path.join(schemasDir, `${kind}.schema.json`), "utf8");
  // Prefix $defs with the kind so generated helper names are per-kind
  // ("map-node" → MapNode) and never collide with DOM globals like Node.
  const schema = JSON.parse(raw.replaceAll('"#/$defs/', `"#/$defs/${kind}-`));
  if (schema.$defs) {
    schema.$defs = Object.fromEntries(
      Object.entries(schema.$defs).map(([k, v]) => [`${kind}-${k}`, v]),
    );
  }
  // Name the interface after the kind, not the schema's $id URL or title.
  delete schema.$id;
  delete schema.title;
  const name = kind[0].toUpperCase() + kind.slice(1) + "Visual";
  names.push(name);
  const ts = await compile(schema, name, { bannerComment: "" });
  parts.push(ts.replace(/^export /gm, "").trimEnd(), "");
}
parts.push(`type Visual = ${names.join(" | ")};`, "");

await mkdir(path.dirname(outFile), { recursive: true });
await writeFile(outFile, parts.join("\n"));
console.log(`wrote ${path.relative(process.cwd(), outFile)}`);
